void fb_draw_char(int x, int y, char c, uint32_t fg, uint32_t bg) {
    uint8_t idx = (uint8_t)c;
    if (idx > 127) idx = 127;
    const uint8_t* glyph = font8x16[idx];
    for (int row = 0; row < 16; row++) {
        int py = y + row;
        if (py < 0 || py >= fb_h) continue;
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            int px = x + col;
            if (px < 0 || px >= fb_w) continue;
            if (bits & (0x80 >> col)) *fb_pixel_ptr(px, py) = fg;
            else if (bg != 0x01000000) *fb_pixel_ptr(px, py) = bg;
        }
    }
}

void fb_draw_string(int x, int y, const char* str, uint32_t fg, uint32_t bg) {
    int ox = x;
    while (*str) {
        if (*str == '\n') { x = ox; y += 16; str++; continue; }
        fb_draw_char(x, y, *str, fg, bg);
        x += 8;
        str++;
    }
}
