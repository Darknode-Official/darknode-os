#include "framebuffer.h"
#include "string.h"

static uint32_t* fb_addr;
static int fb_w, fb_h, fb_pitch;

void fb_init(uint32_t* addr, int width, int height, int pitch) {
    fb_addr = addr;
    fb_w = width;
    fb_h = height;
    fb_pitch = pitch;
}

int fb_width(void)  { return fb_w; }
int fb_height(void) { return fb_h; }

static inline uint32_t* fb_pixel_ptr(int x, int y) {
    return (uint32_t*)((uint8_t*)fb_addr + y * fb_pitch + x * 4);
}

void fb_putpixel(int x, int y, uint32_t color) {
    if (x < 0 || x >= fb_w || y < 0 || y >= fb_h) return;
    *fb_pixel_ptr(x, y) = color;
}

uint32_t fb_getpixel(int x, int y) {
    if (x < 0 || x >= fb_w || y < 0 || y >= fb_h) return 0;
    return *fb_pixel_ptr(x, y);
}

void fb_fill_rect(int x, int y, int w, int h, uint32_t color) {
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > fb_w) w = fb_w - x;
    if (y + h > fb_h) h = fb_h - y;
    if (w <= 0 || h <= 0) return;
    for (int row = y; row < y + h; row++) {
        uint32_t* p = fb_pixel_ptr(x, row);
        for (int i = 0; i < w; i++) p[i] = color;
    }
}

void fb_draw_rect(int x, int y, int w, int h, uint32_t color) {
    for (int i = x; i < x + w; i++) {
        fb_putpixel(i, y, color);
        fb_putpixel(i, y + h - 1, color);
    }
    for (int j = y; j < y + h; j++) {
        fb_putpixel(x, j, color);
        fb_putpixel(x + w - 1, j, color);
    }
}

void fb_draw_line(int x0, int y0, int x1, int y1, uint32_t color) {
    int dx = x1 - x0; if (dx < 0) dx = -dx;
    int dy = y1 - y0; if (dy < 0) dy = -dy;
    int sx = x0 < x1 ? 1 : -1;
    int sy = y0 < y1 ? 1 : -1;
    int err = dx - dy;
    for (;;) {
        fb_putpixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 <  dx) { err += dx; y0 += sy; }
    }
}

void fb_clear(uint32_t color) {
    fb_fill_rect(0, 0, fb_w, fb_h, color);
}

void fb_scroll_region(int x, int y, int w, int h, int lines, uint32_t fill) {
    if (lines <= 0 || lines >= h) { fb_fill_rect(x, y, w, h, fill); return; }
    for (int row = y; row < y + h - lines; row++) {
        uint32_t* dst = fb_pixel_ptr(x, row);
        uint32_t* src = fb_pixel_ptr(x, row + lines);
        memcpy(dst, src, w * 4);
    }
    fb_fill_rect(x, y + h - lines, w, lines, fill);
}

void fb_copy_rect(int dx, int dy, int sx, int sy, int w, int h) {
    if (dy < sy || (dy == sy && dx < sx)) {
        for (int row = 0; row < h; row++) {
            uint32_t* d = fb_pixel_ptr(dx, dy + row);
            uint32_t* s = fb_pixel_ptr(sx, sy + row);
            memcpy(d, s, w * 4);
        }
    } else {
        for (int row = h - 1; row >= 0; row--) {
            uint32_t* d = fb_pixel_ptr(dx, dy + row);
            uint32_t* s = fb_pixel_ptr(sx, sy + row);
            memcpy(d, s, w * 4);
        }
    }
}

